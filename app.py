"""This module serves as the primary entry point for the AutoFix-Agent web interface.
It handles HTTP requests, routes user code input through the validation and AI
analyzer pipeline, and returns stateless JSON responses to the frontend."""

from flask import Flask, jsonify, render_template, request
from agent.analyzer import analyze_and_refactor_code
from agent.validator import validate_python_code

# Initialize the Flask application instance
app = Flask(__name__)


@app.route("/")
def index() -> str:
  """Render the main frontend HTML webpage for the AutoFix-Agent tool.

  Returns:
      str: Rendered HTML template of the user interface.
  """
  return render_template("index.html")


@app.route("/analyze", methods=["POST"])
def analyze() -> tuple:
  """Handle incoming code submission, perform AST syntax validation,

  trigger AI-based analysis/refactoring, and return results statelessly.

  Returns:
      tuple: A JSON response dictionary along with the appropriate HTTP status code.
  """
  # Parse incoming JSON payload from the frontend request
  data = request.json
  source_code = data.get("code", "")

  # Validate that the submitted code string is not empty or composed only of whitespace
  if not source_code.strip():
    return jsonify({"error": "Code input cannot be empty."}), 400

  # Step 1: Validate Python code syntax using the Abstract Syntax Tree (AST) validator
  is_valid, syntax_error = validate_python_code(source_code)

  # Step 2: Forward the source code to the Gemini AI analyzer module
  ai_response = analyze_and_refactor_code(source_code)

  # Check if the AI service encountered any operational or API errors
  if "error" in ai_response:
    return jsonify({"error": ai_response["error"]}), 500

  # Extract the final analysis text generated by the AI model
  analysis_result = ai_response["analysis_result"]

  # Note: Database persistence logic has been completely removed per user configuration (stateless tool)

  # Return a successful structured JSON response containing validation and analysis data
  return jsonify({
      "success": True,
      "syntax_valid": is_valid,
      "syntax_error": syntax_error,
      "analysis": analysis_result,
  })


if __name__ == "__main__":
  # Run the Flask development server with debugging enabled
  app.run(debug=True)